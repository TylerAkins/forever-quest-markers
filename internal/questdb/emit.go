package questdb

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Metadata is written to Database/Metadata.lua and used by release checks.
type Metadata struct {
	Source          string
	Artifact        string
	ArtifactCommit  string
	ArtifactSHA256  string
	PolicySource    string
	PolicyCommit    string
	Version         string
	Flavor          string
	ContractVersion int
	BuildTime       string
	QuestCount      int
	CoordCount      int
	TurnInCount     int
	InstanceCount   int
	YearlyCount     int
}

// EmitDatabase writes the generated addon database files.
func EmitDatabase(outputDir string, records []Record, meta Metadata, instanceTags map[int]int) error {
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(outputDir, "ForeverQuests.lua"), renderQuests(records, meta)); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(outputDir, "QuestTagCorrections.lua"), renderTagCorrections(instanceTags, meta)); err != nil {
		return err
	}
	return writeFile(filepath.Join(outputDir, "Metadata.lua"), renderMetadata(meta))
}

// WriteReport writes the deterministic build report.
func WriteReport(filePath string, report Report) error {
	if err := os.MkdirAll(filepath.Dir(filePath), 0o755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(report, "", "  ")
	if err != nil {
		return err
	}
	data = append(data, '\n')
	return writeFile(filePath, data)
}

func writeFile(filePath string, data []byte) error {
	temp, err := os.CreateTemp(filepath.Dir(filePath), ".questdb-*")
	if err != nil {
		return err
	}
	name := temp.Name()
	if _, err := temp.Write(data); err != nil {
		temp.Close()
		os.Remove(name)
		return err
	}
	if err := temp.Close(); err != nil {
		os.Remove(name)
		return err
	}
	if err := os.Rename(name, filePath); err != nil {
		os.Remove(name)
		return err
	}
	return nil
}

func renderQuests(records []Record, meta Metadata) []byte {
	var builder strings.Builder
	builder.WriteString("-- AUTO-GENERATED FILE\n")
	builder.WriteString("-- DO NOT EDIT MANUALLY\n")
	builder.WriteString("-- Source: QuestieDB-Forever\n")
	if meta.ArtifactCommit != "" {
		builder.WriteString("-- Artifact commit: " + meta.ArtifactCommit + "\n")
	}
	if meta.ArtifactSHA256 != "" {
		builder.WriteString("-- Artifact SHA-256: " + meta.ArtifactSHA256 + "\n")
	}
	if meta.PolicyCommit != "" {
		builder.WriteString("-- Policy commit: " + meta.PolicyCommit + "\n")
	}
	builder.WriteString("-- Generated by cmd/fqp build-db\n")
	builder.WriteString("--\n")
	builder.WriteString("-- Compact quest-start records keyed by questID. Coordinates use Questie's\n")
	builder.WriteString("-- 0-100 UiMapID space (the same system as Blizzard world-map pins).\n\n")
	builder.WriteString("local ADDON_NAME, ns = ...\n")
	builder.WriteString("ns.Quests = {\n")
	for _, record := range records {
		builder.WriteString("\t[")
		builder.WriteString(strconv.Itoa(record.QuestID))
		builder.WriteString("] = { ")
		builder.WriteString(renderRecord(record))
		builder.WriteString(" },\n")
	}
	builder.WriteString("}\n\n")
	builder.WriteString("ns.ByMap = {\n")
	byMap := map[int][]int{}
	for _, record := range records {
		for _, coord := range record.Coords {
			byMap[coord.MapID] = append(byMap[coord.MapID], record.QuestID)
		}
	}
	mapIDs := make([]int, 0, len(byMap))
	for mapID := range byMap {
		mapIDs = append(mapIDs, mapID)
	}
	sort.Ints(mapIDs)
	for _, mapID := range mapIDs {
		ids := uniqueSorted(byMap[mapID])
		builder.WriteString("\t[")
		builder.WriteString(strconv.Itoa(mapID))
		builder.WriteString("] = { ")
		writeIntList(&builder, ids)
		builder.WriteString(" },\n")
	}
	builder.WriteString("}\n")
	return []byte(builder.String())
}

func renderRecord(record Record) string {
	var fields []string
	add := func(key, value string) {
		fields = append(fields, key+"="+value)
	}
	if len(record.Coords) > 0 {
		first := record.Coords[0]
		add("mapID", strconv.Itoa(first.MapID))
		add("x", formatFloat(first.X))
		add("y", formatFloat(first.Y))
		if len(record.Coords) > 1 {
			var builder strings.Builder
			builder.WriteString("{ ")
			for index, coord := range record.Coords[1:] {
				if index > 0 {
					builder.WriteString(", ")
				}
				builder.WriteString("{ ")
				builder.WriteString(formatFloat(coord.X))
				builder.WriteString(", ")
				builder.WriteString(formatFloat(coord.Y))
				builder.WriteString(", ")
				builder.WriteString(strconv.Itoa(coord.MapID))
				builder.WriteString(" }")
			}
			builder.WriteString(" }")
			add("coords", builder.String())
		}
	}
	if record.QG != 0 {
		add("qg", strconv.Itoa(record.QG))
	}
	if len(record.QGs) > 0 {
		add("qgs", renderIntList(record.QGs))
	}
	if len(record.TurnIns) > 0 {
		add("turnIns", renderIntList(record.TurnIns))
	}
	if len(record.TurnInObjects) > 0 {
		add("turnInObjects", renderIntList(record.TurnInObjects))
	}
	if len(record.SourceQuestGroup) > 0 {
		add("sourceQuestGroup", renderIntList(record.SourceQuestGroup))
	}
	if len(record.SourceQuestSingle) > 0 {
		add("sourceQuestSingle", renderIntList(record.SourceQuestSingle))
		add("sourceQuestNumRequired", strconv.Itoa(record.SourceQuestNumRequired))
	}
	if len(record.AltQuests) > 0 {
		add("altQuests", renderIntList(record.AltQuests))
	}
	if len(record.Races) > 0 {
		add("races", renderIntList(record.Races))
	}
	if len(record.Classes) > 0 {
		add("classes", renderIntList(record.Classes))
	}
	if record.RequireSkill != nil && record.RequireSkill.ID != 0 {
		add("requireSkill", strconv.Itoa(record.RequireSkill.ID))
	}
	if record.Faction != "" {
		add("faction", quoteLua(record.Faction))
	}
	if record.MinLevel > 0 {
		add("minLevel", strconv.Itoa(record.MinLevel))
	}
	if record.IsYearly {
		add("isYearly", "true")
	}
	if record.Event != 0 {
		add("event", strconv.Itoa(record.Event))
	}
	if record.Repeatable {
		add("repeatable", "true")
	}
	if record.IsMonthly {
		add("isMonthly", "true")
	}
	if record.IsBreadcrumb {
		add("isBreadcrumb", "true")
	}
	if record.IsInstanceQuest {
		add("isInstanceQuest", "true")
	}
	if record.Title != "" {
		add("title", quoteLua(record.Title))
	}
	return strings.Join(fields, ", ")
}

func renderIntList(values []int) string {
	var builder strings.Builder
	builder.WriteString("{ ")
	writeIntList(&builder, values)
	builder.WriteString(" }")
	return builder.String()
}

func writeIntList(builder *strings.Builder, values []int) {
	for index, value := range values {
		if index > 0 {
			builder.WriteString(", ")
		}
		builder.WriteString(strconv.Itoa(value))
	}
}

func formatFloat(value float64) string {
	value = float64(int64(value*100+0.5)) / 100
	return strconv.FormatFloat(value, 'f', -1, 64)
}

func quoteLua(value string) string {
	var builder strings.Builder
	builder.WriteByte('"')
	for _, character := range value {
		switch character {
		case '\\':
			builder.WriteString(`\\`)
		case '"':
			builder.WriteString(`\"`)
		case '\n':
			builder.WriteString(`\n`)
		case '\r':
			builder.WriteString(`\r`)
		case '\t':
			builder.WriteString(`\t`)
		default:
			if character < 32 {
				builder.WriteString(fmt.Sprintf(`\%03d`, character))
			} else {
				builder.WriteRune(character)
			}
		}
	}
	builder.WriteByte('"')
	return builder.String()
}

func renderTagCorrections(tags map[int]int, meta Metadata) []byte {
	var builder strings.Builder
	builder.WriteString("-- AUTO-GENERATED FILE\n")
	builder.WriteString("-- DO NOT EDIT MANUALLY\n")
	builder.WriteString("-- Source: Questie/Questie questTagInfoCorrections.lua\n")
	if meta.PolicyCommit != "" {
		builder.WriteString("-- Policy commit: " + meta.PolicyCommit + "\n")
	}
	builder.WriteString("-- Generated by cmd/fqp build-db\n\n")
	builder.WriteString("local ADDON_NAME, ns = ...\n")
	builder.WriteString("ns.QuestTagCorrections = {\n")
	ids := make([]int, 0, len(tags))
	for id := range tags {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	for _, id := range ids {
		builder.WriteString("\t[")
		builder.WriteString(strconv.Itoa(id))
		builder.WriteString("] = ")
		builder.WriteString(strconv.Itoa(tags[id]))
		builder.WriteString(",\n")
	}
	builder.WriteString("}\n")
	return []byte(builder.String())
}

func renderMetadata(meta Metadata) []byte {
	var builder strings.Builder
	builder.WriteString("-- AUTO-GENERATED FILE\n")
	builder.WriteString("-- DO NOT EDIT MANUALLY\n")
	builder.WriteString("-- Source: QuestieDB-Forever\n")
	builder.WriteString("-- Generated by cmd/fqp build-db\n\n")
	builder.WriteString("local ADDON_NAME, ns = ...\n")
	builder.WriteString("ns.Metadata = {\n")
	writeMetadataField := func(key, value string) {
		builder.WriteString("\t")
		builder.WriteString(key)
		builder.WriteString(" = ")
		builder.WriteString(value)
		builder.WriteString(",\n")
	}
	writeMetadataField("source", quoteLua(meta.Source))
	if meta.Artifact != "" {
		writeMetadataField("artifact", quoteLua(meta.Artifact))
	}
	writeMetadataField("artifactCommit", quoteLua(meta.ArtifactCommit))
	if meta.ArtifactSHA256 != "" {
		writeMetadataField("artifactSHA256", quoteLua(meta.ArtifactSHA256))
	}
	writeMetadataField("policySource", quoteLua(meta.PolicySource))
	if meta.PolicyCommit != "" {
		writeMetadataField("policyCommit", quoteLua(meta.PolicyCommit))
	}
	writeMetadataField("version", quoteLua(meta.Version))
	writeMetadataField("flavor", quoteLua(meta.Flavor))
	writeMetadataField("contractVersion", strconv.Itoa(meta.ContractVersion))
	if meta.BuildTime != "" {
		writeMetadataField("buildTime", quoteLua(meta.BuildTime))
	}
	writeMetadataField("questCount", strconv.Itoa(meta.QuestCount))
	writeMetadataField("coordCount", strconv.Itoa(meta.CoordCount))
	writeMetadataField("turnInCount", strconv.Itoa(meta.TurnInCount))
	writeMetadataField("instanceQuestCount", strconv.Itoa(meta.InstanceCount))
	writeMetadataField("yearlyQuestCount", strconv.Itoa(meta.YearlyCount))
	writeMetadataField("generatedBy", quoteLua("cmd/fqp build-db"))
	builder.WriteString("}\n")
	return []byte(builder.String())
}
