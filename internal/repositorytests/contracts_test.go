func root(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("could not locate repository test source")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", ".."))
}

func read(t *testing.T, base, path string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(base, path))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestAddonTOCAndPackagingContract(t *testing.T) {
	base := root(t)
	toc := read(t, base, "ForeverQuestPins.toc")
	for _, required := range []string{
		"## Interface: 16001",
		"## SavedVariables: ForeverQuestPinsDB, ForeverQuestPinsDB_Settings",
		"## SavedVariablesPerCharacter: ForeverQuestPinsCharDB, ForeverQuestPinsCharacterSettings",
		"## X-License: GPL-3.0-or-later",
		"## X-Website: https://github.com/TylerAkins/forever-quest-markers",
		`Database\QuestTagCorrections.lua`,
	} {
		if !strings.Contains(toc, required) {
			t.Errorf("TOC missing %q", required)
		}
	}
	for before, after := range map[string]string{
		"Database\\ForeverQuests.lua":       "Database\\QuestTagCorrections.lua",
		"Database\\QuestTagCorrections.lua": "Config.lua",
		"Config.lua":                        "HiddenQuests.lua",
		"HiddenQuests.lua":                  "Eligibility.lua",
		"Eligibility.lua":                   "Waypoints.lua",
	} {
		if strings.Index(toc, before) < 0 || strings.Index(toc, after) < strings.Index(toc, before) {
			t.Errorf("TOC load order does not place %s before %s", before, after)
		}
	}
	metadata := read(t, base, ".pkgmeta")
	for _, excluded := range []string{"tests", "cmd", "internal", "go.mod", "go.sum", "Database/build_report.json"} {
		if !strings.Contains(metadata, "- "+excluded) {
			t.Errorf("packager does not exclude %s", excluded)
		}
	}
}

func TestGeneratedDatabaseMatchesReportAndStableContracts(t *testing.T) {
	base := root(t)
	quests := read(t, base, "Database/ForeverQuests.lua")
	metadata := read(t, base, "Database/Metadata.lua")
	tagCorrections := read(t, base, "Database/QuestTagCorrections.lua")
	var report struct {
		Artifact struct {
			Commit   string `json:"commit"`
			SHA256   string `json:"sha256"`
			Flavor   string `json:"flavor"`
			Contract int    `json:"contract_version"`
		} `json:"artifact"`
		Policy struct {
			Commit string `json:"commit"`
		} `json:"policy"`
		PolicyCoverage struct {
			YearlyMarked   int `json:"yearly_marked"`
			InstanceStatic int `json:"instance_static"`
		} `json:"policy_coverage"`
		Counts struct {
			Quests              int `json:"quests"`
			QuestsWithCoords    int `json:"quests_with_coords"`
			CoordPins           int `json:"coord_pins"`
			QuestsWithTurnIns   int `json:"quests_with_turn_ins"`
			TurnInNPCs          int `json:"turn_in_npcs"`
			TurnInObjects       int `json:"turn_in_objects"`
			InstanceQuests      int `json:"instance_quests"`
			YearlyQuests        int `json:"yearly_quests"`
			RepeatableQuests    int `json:"repeatable_quests"`
			MonthlyQuests       int `json:"monthly_quests"`
			BreadcrumbQuests    int `json:"breadcrumb_quests"`
			QuestsWithRaces     int `json:"quests_with_races"`
			QuestsWithClasses   int `json:"quests_with_classes"`
			QuestsWithSkill     int `json:"quests_with_skill"`
			QuestsWithPrereqs   int `json:"quests_with_prereqs"`
			QuestsWithAltQuests int `json:"quests_with_alt_quests"`
		} `json:"counts"`
		StartGaps map[string]int `json:"start_gaps"`
	}
	if err := json.Unmarshal([]byte(read(t, base, "Database/build_report.json")), &report); err != nil {
		t.Fatal(err)
	}
	if report.Artifact.Flavor != "Forever" || report.Artifact.Contract != 4 {
		t.Fatalf("unexpected artifact contract: %+v", report.Artifact)
	}
	for _, content := range []string{quests, metadata, tagCorrections} {
		for _, header := range []string{"-- AUTO-GENERATED FILE", "-- DO NOT EDIT MANUALLY", "-- Generated by cmd/fqp build-db"} {
			if !strings.Contains(content, header) {
				t.Errorf("generated output missing %q", header)
			}
		}
	}
	if !strings.Contains(quests, "-- Source: QuestieDB-Forever") ||
		!strings.Contains(quests, "-- Artifact commit: "+report.Artifact.Commit) ||
		!strings.Contains(quests, "-- Artifact SHA-256: "+report.Artifact.SHA256) ||
		!strings.Contains(quests, "-- Policy commit: "+report.Policy.Commit) {
		t.Fatal("quest database headers disagree with the build report provenance")
	}
	for _, contract := range []string{
		`source = "QuestieDB-Forever"`,
		`artifactCommit = "` + report.Artifact.Commit + `"`,
		`artifactSHA256 = "` + report.Artifact.SHA256 + `"`,
		`policyCommit = "` + report.Policy.Commit + `"`,
		`flavor = "Forever"`,
		`contractVersion = 4`,
		`questCount = ` + strconv.Itoa(report.Counts.Quests),
		`coordCount = ` + strconv.Itoa(report.Counts.CoordPins),
	} {
		if !strings.Contains(metadata, contract) {
			t.Errorf("metadata missing %q", contract)
		}
	}
	if !strings.Contains(tagCorrections, "-- Policy commit: "+report.Policy.Commit) {
		t.Fatal("tag correction output disagrees with the build report policy commit")
	}
	questPart := strings.SplitN(quests, "ns.ByMap = {", 2)[0]
	questRows := regexp.MustCompile(`(?m)^\s*\[(\d+)\] = \{([^\n]*)`).FindAllStringSubmatch(questPart, -1)
	if len(questRows) != report.Counts.Quests {
		t.Fatalf("database has %d quest records, report says %d", len(questRows), report.Counts.Quests)
	}
	questSet := make(map[int]struct{}, len(questRows))
	withCoords := 0
	for _, match := range questRows {
		id, _ := strconv.Atoi(match[1])
		questSet[id] = struct{}{}
		if strings.Contains(match[2], "mapID=") {
			withCoords++
		}
	}
	if withCoords != report.Counts.QuestsWithCoords {
		t.Fatalf("database has %d quest records with coordinates, report says %d", withCoords, report.Counts.QuestsWithCoords)
	}
	byMap := strings.SplitN(quests, "ns.ByMap = {", 2)
	if len(byMap) != 2 {
		t.Fatal("generated database is missing its map index")
	}
	mapRows := regexp.MustCompile(`(?m)^\s*\[(\d+)\] = \{([^}]*)\}`).FindAllStringSubmatch(byMap[1], -1)
	for _, row := range mapRows {
		for _, value := range regexp.MustCompile(`\d+`).FindAllString(row[2], -1) {
			id, _ := strconv.Atoi(value)
			if _, exists := questSet[id]; !exists {
				t.Errorf("map index references missing quest %d", id)
			}
		}
	}
	flagCounts := map[string]int{
		"isAttunement":    countMatches(questPart, `isAttunement=true`),
		"isInstanceQuest": countMatches(questPart, `isInstanceQuest=true`),
		"isYearly":        countMatches(questPart, `isYearly=true`),
		"repeatable":      countMatches(questPart, `repeatable=true`),
		"isMonthly":       countMatches(questPart, `isMonthly=true`),
		"isBreadcrumb":    countMatches(questPart, `isBreadcrumb=true`),
	}
	if flagCounts["isAttunement"] != 0 {
		t.Fatal("ATT-only isAttunement flag survived generation")
	}
	if flagCounts["isInstanceQuest"] != report.Counts.InstanceQuests {
		t.Fatalf("isInstanceQuest count = %d, report says %d", flagCounts["isInstanceQuest"], report.Counts.InstanceQuests)
	}
	if flagCounts["isYearly"] != report.Counts.YearlyQuests {
		t.Fatalf("isYearly count = %d, report says %d", flagCounts["isYearly"], report.Counts.YearlyQuests)
	}
	if flagCounts["repeatable"] != report.Counts.RepeatableQuests {
		t.Fatalf("repeatable count = %d, report says %d", flagCounts["repeatable"], report.Counts.RepeatableQuests)
	}
	if flagCounts["isMonthly"] != report.Counts.MonthlyQuests {
		t.Fatalf("isMonthly count = %d, report says %d", flagCounts["isMonthly"], report.Counts.MonthlyQuests)
	}
	if flagCounts["isBreadcrumb"] != report.Counts.BreadcrumbQuests {
		t.Fatalf("isBreadcrumb count = %d, report says %d", flagCounts["isBreadcrumb"], report.Counts.BreadcrumbQuests)
	}
	if report.PolicyCoverage.YearlyMarked != report.Counts.YearlyQuests {
		t.Fatalf("yearly policy coverage = %d, report counts %d", report.PolicyCoverage.YearlyMarked, report.Counts.YearlyQuests)
	}
	if report.PolicyCoverage.InstanceStatic != report.Counts.InstanceQuests {
		t.Fatalf("instance policy coverage = %d, report counts %d", report.PolicyCoverage.InstanceStatic, report.Counts.InstanceQuests)
	}
	if report.Counts.TurnInNPCs <= 0 || report.Counts.TurnInObjects <= 0 || report.Counts.QuestsWithTurnIns <= 0 {
		t.Fatal("generation produced no turn-in targets")
	}
	for questID, pattern := range map[string]string{
		"754":   `\[754\] = \{ mapID=1412, x=47\.52, y=63\.58`,
		"8673":  `\[8673\] = \{[^\n]*isYearly=true`,
		"17":    `\[17\] = \{[^\n]*isInstanceQuest=true`,
		"96102": `\[96102\] = \{[^\n]*requireSkill=197`,
	} {
		if !regexp.MustCompile(pattern).MatchString(questPart) {
			t.Errorf("quest %s does not match its generated-data contract", questID)
		}
	}
	for _, retired := range []string{"attTitle", "isAttunement", "databaseCommit", "attCommit", "event=", "isDaily=", "isWeekly=", "isWorldQuest="} {
		if strings.Contains(quests, retired) || strings.Contains(metadata, retired) {
			t.Errorf("generated files contain retired field %q", retired)
		}
	}
	if report.StartGaps["unmapped_zone"] != 0 || report.StartGaps["no_dungeon_entrance"] != 0 || report.StartGaps["missing_entity"] != 0 {
		t.Fatalf("build report contains unresolved data errors: %v", report.StartGaps)
	}
}

func countMatches(text, pattern string) int {
	return len(regexp.MustCompile(pattern).FindAllString(text, -1))
}

func TestWorkflowsRunGoToolsAndRetainLuaJITTestsWithoutPython(t *testing.T) {
	base := root(t)
	for _, workflow := range []string{"ci.yml", "release.yml", "update-questie-db.yml", "update-forever-interface.yml"} {
		text := read(t, base, filepath.Join(".github", "workflows", workflow))
		if strings.Contains(text, "actions/setup-python") || strings.Contains(text, "python3 ") || strings.Contains(text, "pip install") {
			t.Errorf("%s still depends on Python", workflow)
		}
		if !strings.Contains(text, "actions/setup-go@") || !strings.Contains(text, "go test ./...") {
			t.Errorf("%s does not set up Go and run the Go tests", workflow)
		}
		if !strings.Contains(text, "luajit") {
			t.Errorf("%s does not install LuaJIT for runtime tests", workflow)
		}
	}
	if _, err := os.Stat(filepath.Join(base, ".github", "workflows", "update-att-db.yml")); err == nil {
		t.Fatal("obsolete ATT update workflow still exists")
	}
	if strings.Contains(read(t, base, "go.mod"), "lupa") {
		t.Fatal("Go module still depends on Lupa")
	}
}

func TestLuaFilesAndDocumentationDescribeGoTooling(t *testing.T) {
	base := root(t)
	toc := read(t, base, "ForeverQuestPins.toc")
	for _, line := range strings.Split(toc, "\n") {
		entry := strings.TrimSpace(line)
		if entry == "" || strings.HasPrefix(entry, "#") {
			continue
		}
		path := filepath.Join(base, filepath.FromSlash(strings.ReplaceAll(entry, `\`, "/")))
		if _, err := os.Stat(path); err != nil {
			t.Errorf("TOC entry %s does not exist: %v", entry, err)
		}
	}
	readme := read(t, base, "README.md")
	development := read(t, base, "docs/DEVELOPMENT.md")
	for _, text := range []string{readme, development} {
		if strings.Contains(text, ".py") || strings.Contains(text, "python3") {
			t.Error("active documentation still points to Python tools")
		}
	}
	for _, command := range []string{"build-db", "release", "update-interface", "compile-addon", "repair-settings", "generate-icon"} {
		if !strings.Contains(readme+development, "./cmd/fqp "+command) {
			t.Errorf("documentation omits Go command %s", command)
		}
	}
	if !strings.Contains(readme+development, "--questiedb") || !strings.Contains(readme+development, "QuestieDB") {
		t.Error("documentation does not describe the QuestieDB build source")
	}
	for _, path := range []string{"cmd/fqp/main.go", "internal/questdb/build.go", "internal/questiedb/artifact.go", "internal/questiepolicy/policy.go", "internal/release/release.go", "internal/foreverupdate/update.go", "internal/addontools/addontools.go"} {
		if _, err := os.Stat(filepath.Join(base, path)); err != nil {
			t.Errorf("missing Go implementation %s", path)
		}
	}
	for _, retired := range []string{"internal/attdsl", "tools/att_dsl"} {
		if _, err := os.Stat(filepath.Join(base, retired)); err == nil {
			t.Errorf("obsolete ATT implementation still exists at %s", retired)
		}
	}
}

func TestAddonSourceKeepsImportantRuntimeContracts(t *testing.T) {
	base := root(t)
	eligibility := read(t, base, "Eligibility.lua")
	for _, contract := range []string{
		"function ns.IsQuestAvailable(questID, data)",
		"function ns.IsSourceSatisfied(questID)",
		"function ns.HasQuestGiver(data)",
		"function ns.HasRequiredSkill(requiredSkill)",
		"function ns.IsInstanceQuest(questID, data)",
		"function ns.InvalidateInstanceQuestCache(questID)",
		"GetAllCompletedQuestIDs",
		"function ns.NoteQuestAccepted",
		"data.title",
		"sourceQuestGroup",
		"sourceQuestSingle",
	} {
		if !strings.Contains(eligibility, contract) {
			t.Errorf("Eligibility.lua missing %q", contract)
		}
	}
	if strings.Contains(eligibility, "data.attTitle") || strings.Contains(eligibility, "isAttunement") {
		t.Fatal("Eligibility.lua still reads retired ATT fields")
	}
	mapPins := read(t, base, "MapPins.lua")
	for _, contract := range []string{
		`NORMAL_ICON_ATLAS = "QuestNormal"`,
		`REPEATABLE_ICON_ATLAS = "QuestDaily"`,
		`TrySetTintedAtlas(tex, NORMAL_ICON_ATLAS, 1.00, 0.32, 0.08)`,
		`Media\\QuestAvailable`,
		`Media\\QuestRepeatable`,
		`Media\\QuestAttunement`,
		`local function IsInstanceOnly(pin)`,
		`ns.IsInstanceQuest(quest.id, quest.data)`,
	} {
		if !strings.Contains(mapPins, contract) {
			t.Errorf("MapPins.lua missing %q", contract)
		}
	}
	if strings.Contains(mapPins, "isAttunement") || strings.Contains(mapPins, "IsAttunementOnly") {
		t.Fatal("MapPins.lua still uses ATT attunement terms")
	}
	waypoints := read(t, base, "Waypoints.lua")
	if strings.Contains(waypoints, "HereBeDragons") || strings.Contains(waypoints, "LibStub") {
		t.Fatal("waypoint implementation gained a HereBeDragons dependency")
	}
	for _, contract := range []string{"C_Map.SetUserWaypoint", "C_SuperTrack.SetSuperTrackedQuestID", "TomTom.AddWaypoint"} {
		if !strings.Contains(waypoints, contract) {
			t.Errorf("Waypoints.lua missing %q", contract)
		}
	}
	tooltips := read(t, base, "NPCTooltips.lua")
	for _, contract := range []string{"function Tooltips:GetTurnInRows(npcID)", "turnIns", "marker = \"?\"", "fqpQuestRows"} {
		if !strings.Contains(tooltips, contract) {
			t.Errorf("NPCTooltips.lua missing %q", contract)
		}
	}
	config := read(t, base, "Config.lua")
	for _, contract := range []string{"showNPCTooltips = true", `key == "iconScale"`, `key == "showInGameNavigation"`, "Dungeon, raid, and attunement quest starts."} {
		if !strings.Contains(config, contract) {
			t.Errorf("Config.lua missing %q", contract)
		}
	}
	core := read(t, base, "Core.lua")
	if !strings.Contains(core, `"SKILL_LINES_CHANGED"`) || !strings.Contains(core, "NPCTooltips:Initialize") || !strings.Contains(core, "InvalidateInstanceQuestCache") {
		t.Fatal("Core.lua is missing a required refresh, tooltip, or instance-cache hook")
	}
}
