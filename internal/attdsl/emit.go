const generatedBy = "cmd/fqp build-db"
const attSourceURL = "https://github.com/ATTWoWAddon/AllTheThings.git"

func NormalizeATTTitle(raw string) string {
	title := strings.TrimSpace(raw)
	trail := regexpTrailingFaction
	title = trail.ReplaceAllString(title, "")
	title = regexpLevelBracket.ReplaceAllString(title, " ")
	return strings.Join(strings.Fields(title), " ")
}

func ApplyTitles(source string, result *ExtractResult) {
	for _, line := range strings.Split(source, "\n") {
		match := regexpQuestTitle.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		id, err := strconv.Atoi(match[1])
		if err != nil {
			continue
		}
		title := NormalizeATTTitle(match[2])
		if record := result.Quests[id]; record != nil && record.ATTTitle == "" && title != "" {
			record.ATTTitle = title
		}
	}
}

var regexpTrailingFaction = regexpMustCompile(`(?i)\s*\((?:Horde|Alliance)\)\s*$`)
var regexpLevelBracket = regexpMustCompile(`\s*\[Level\s+[^\]]+\]\s*`)
var regexpQuestTitle = regexpMustCompile(`\bq\(\s*(\d+)\s*,\s*\{[^\n]*--\s*(.+)`)

func EmitLuaDatabase(quests map[int]*QuestRecord, attSHA string) string {
	lines := []string{"-- AUTO-GENERATED FILE", "-- DO NOT EDIT MANUALLY", "-- Source: ATTWoWAddon/AllTheThings", "-- ATT commit: " + attSHA, "-- Generated by " + generatedBy, "--", "-- Compact quest-start records keyed by questID. Coordinates use ATT's", "-- 0-100 UiMapID space (the same system as Blizzard world-map pins).", "", "local ADDON_NAME, ns = ...", "ns.Quests = {"}
	ids := sortedQuestIDs(quests)
	for _, id := range ids {
		lines = append(lines, fmt.Sprintf("\t[%d] = { %s },", id, questBody(quests[id])))
	}
	lines = append(lines, "}", "", "ns.ByMap = {")
	byMap := map[int][]int{}
	for _, id := range ids {
		seen := map[int]bool{}
		for _, coord := range quests[id].Coords {
			if !seen[coord.MapID] {
				byMap[coord.MapID] = append(byMap[coord.MapID], id)
				seen[coord.MapID] = true
			}
		}
	}
	mapIDs := make([]int, 0, len(byMap))
	for id := range byMap {
		mapIDs = append(mapIDs, id)
	}
	sort.Ints(mapIDs)
	for _, mapID := range mapIDs {
		lines = append(lines, fmt.Sprintf("\t[%d] = { %s },", mapID, intList(byMap[mapID])))
	}
	lines = append(lines, "}", "")
	return strings.Join(lines, "\n") + "\n"
}

func EmitMetadata(attSHA string, stats map[string]any) string {
	return fmt.Sprintf("-- AUTO-GENERATED FILE\n-- DO NOT EDIT MANUALLY\n-- Source: ATTWoWAddon/AllTheThings\n-- ATT commit: %s\n-- Generated by %s\n\nlocal ADDON_NAME, ns = ...\nns.Metadata = {\n\tsource = \"ATTWoWAddon/AllTheThings\",\n\tattCommit = \"%s\",\n\tattRef = \"%s\",\n\tquestCount = %d,\n\tcoordCount = %d,\n\tattunementCount = %d,\n\tfilesParsed = %d,\n\tgeneratedBy = \"%s\",\n}\n", attSHA, generatedBy, attSHA, escapeLua(attSourceURL), statInt(stats, "quests_emitted"), statInt(stats, "coord_pins"), statInt(stats, "attunement_quests"), statInt(stats, "files_parsed"), generatedBy)
}

func EmitReport(stats map[string]any) ([]byte, error) {
	var buffer bytes.Buffer
	encoder := json.NewEncoder(&buffer)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(stats); err != nil {
		return nil, err
	}
	return bytes.TrimSuffix(buffer.Bytes(), []byte("\n")), nil
}

func WriteOutputs(output string, quests map[int]*QuestRecord, attSHA string, stats map[string]any) error {
	if err := os.MkdirAll(output, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(output, "ForeverQuests.lua"), []byte(EmitLuaDatabase(quests, attSHA)), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(output, "Metadata.lua"), []byte(EmitMetadata(attSHA, stats)), 0o644); err != nil {
		return err
	}
	report, err := EmitReport(stats)
	if err != nil {
		return err
	}
	report = append(report, '\n')
	return os.WriteFile(filepath.Join(output, "build_report.json"), report, 0o644)
}

func questBody(record *QuestRecord) string {
	parts := []string{}
	primary := record.Coords[0]
	parts = append(parts, fmt.Sprintf("mapID=%d", primary.MapID), "x="+formatNumber(primary.X), "y="+formatNumber(primary.Y))
	if len(record.Coords) > 1 {
		coords := make([]string, 0, len(record.Coords))
		for _, coord := range record.Coords {
			coords = append(coords, fmt.Sprintf("{ %s, %s, %d }", formatNumber(coord.X), formatNumber(coord.Y), coord.MapID))
		}
		parts = append(parts, "coords={ "+strings.Join(coords, ", ")+" }")
	}
	if len(record.QGs) == 1 {
		parts = append(parts, fmt.Sprintf("qg=%d", record.QGs[0]))
	} else if len(record.QGs) > 1 {
		parts = append(parts, "qgs="+luaIntList(record.QGs))
	}
	if len(record.SourceQuests) > 0 {
		parts = append(parts, "sourceQuests="+luaIntList(record.SourceQuests))
	}
	if record.SourceQuestNumRequired != nil {
		parts = append(parts, fmt.Sprintf("sourceQuestNumRequired=%d", *record.SourceQuestNumRequired))
	}
	if len(record.AltQuests) > 0 {
		parts = append(parts, "altQuests="+luaIntList(record.AltQuests))
	}
	if record.Faction != "" {
		parts = append(parts, "faction=\""+escapeLua(record.Faction)+"\"")
	}
	if len(record.Races) > 0 {
		parts = append(parts, "races="+luaIntList(record.Races))
	}
	if len(record.Classes) > 0 {
		parts = append(parts, "classes="+luaIntList(record.Classes))
	}
	switch skill := record.RequiredSkill.(type) {
	case int:
		parts = append(parts, fmt.Sprintf("requireSkill=%d", skill))
	case string:
		parts = append(parts, "requireSkill=\""+escapeLua(skill)+"\"")
	}
	if record.MinLevel != nil {
		parts = append(parts, fmt.Sprintf("minLevel=%d", *record.MinLevel))
	}
	if record.MaxLevel != nil {
		parts = append(parts, fmt.Sprintf("maxLevel=%d", *record.MaxLevel))
	}
	flags := []struct {
		name  string
		value bool
	}{{"isBreadcrumb", record.IsBreadcrumb}, {"repeatable", record.Repeatable}, {"isDaily", record.IsDaily}, {"isWeekly", record.IsWeekly}, {"isYearly", record.IsYearly}, {"isMonthly", record.IsMonthly}, {"isWarEffort", record.IsWarEffort}, {"isAttunement", record.IsAttunement}, {"isInstanceQuest", record.IsInstanceQuest}}
	for _, flag := range flags {
		if flag.value {
			parts = append(parts, flag.name+"=true")
		}
	}
	if record.Event != nil {
		parts = append(parts, fmt.Sprintf("event=%d", *record.Event))
	}
	if record.ATTTitle != "" {
		parts = append(parts, "attTitle=\""+escapeLua(record.ATTTitle)+"\"")
	}
	return strings.Join(parts, ", ")
}

func sortedQuestIDs(quests map[int]*QuestRecord) []int {
	ids := make([]int, 0, len(quests))
	for id := range quests {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	return ids
}
func intList(values []int) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = strconv.Itoa(value)
	}
	return strings.Join(parts, ", ")
}
func luaIntList(values []int) string { return "{ " + intList(values) + " }" }
func formatNumber(value float64) string {
	if math.Trunc(value) == value {
		return strconv.FormatInt(int64(value), 10)
	}
	text := strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.4f", value), "0"), ".")
	return text
}
func escapeLua(value string) string {
	return strings.ReplaceAll(strings.ReplaceAll(value, `\`, `\\`), `"`, `\"`)
}
func statInt(stats map[string]any, key string) int {
	switch value := stats[key].(type) {
	case int:
		return value
	case int64:
		return int(value)
	case float64:
		return int(value)
	}
	return 0
}
func regexpMustCompile(pattern string) *regexp.Regexp { return regexp.MustCompile(pattern) }
